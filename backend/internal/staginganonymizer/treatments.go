package staginganonymizer

// Treatment says what the anonymizer does with a table's rows or with one column.
type Treatment string

// Column treatments.
const (
	// System marks values the system sets: states, kinds, codes, reference numbers, hashes, identifiers.
	System Treatment = "kept: set by the system, not about a person"
	// Catalog marks configuration and catalog content that describes the makerspace, not a person.
	Catalog       Treatment = "kept: catalog or configuration content"
	FakeName      Treatment = "replaced by a stable fake name"
	FakeEmail     Treatment = "replaced by an example.invalid address"
	Cleared       Treatment = "cleared"
	Neutral       Treatment = "replaced by a neutral text"
	FileName      Treatment = "replaced by a neutral name that keeps the extension"
	RandomToken   Treatment = "replaced by the digest of a random value"
	Mailpit       Treatment = "pointed at staging's Mailpit"
	ProductionKey Treatment = "cleared: encrypted with production's keys"
)

// Table treatments for tables whose rows are all deleted.
const (
	EmptiedCredential       Treatment = "emptied: credentials and token digests" //nolint:gosec // a label, not a credential
	EmptiedSignInState      Treatment = "emptied: transient sign-in and pairing state"
	EmptiedIdentityProvider Treatment = "emptied: bound to production's identity provider"
	EmptiedHistory          Treatment = "emptied: log, notification and delivery history"
	EmptiedSubjectRequest   Treatment = "emptied: data subject requests"
	EmptiedPersonalFile     Treatment = "emptied: files that belong to people"
	EmptiedStorageQueue     Treatment = "emptied: names production storage keys"
)

// Table is how the anonymizer treats one table.
type Table struct {
	Name string
	// Emptied is set when every row is deleted.
	Emptied Treatment
	// Columns covers every column of a kept table that can hold text: text, bytea, jsonb and arrays. Other
	// types (UUIDs, numbers, booleans, dates and times) cannot hold names, contact data or secrets and stay;
	// references keep pointing at the anonymized rows.
	Columns map[string]Treatment
}

