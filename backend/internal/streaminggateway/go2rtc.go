// RenderOptions are the deployment-specific parts of the go2rtc configuration.
type RenderOptions struct {
	// APIListen is go2rtc's HTTP API address. It must only be reachable from the gateway.
	APIListen string
	// WebRTCListen is the WebRTC media port (TCP and UDP).
	WebRTCListen string
	// WebRTCCandidates are the host:port addresses go2rtc advertises as ICE candidates. Inside a
	// container go2rtc only sees its container address, so the LAN address of the Docker host must
	// be given here.
	WebRTCCandidates []string
	// LogLevel is go2rtc's log level; only "error" and "fatal" are accepted (see ValidLogLevel).
	LogLevel string
	// APIUsername and APIPassword protect go2rtc's HTTP API (HTTP Basic). They are required: the
	// generated configuration refuses to render an unauthenticated API.
	APIUsername, APIPassword string
}

// ValidLogLevel reports whether level may be used. go2rtc logs stream sources, which carry the
// printers' LAN access codes, at the more verbose levels, so only error and fatal are allowed.
func ValidLogLevel(level string) bool { return level == "error" || level == "fatal" }

// apiAllowedPaths are the only API paths go2rtc serves: the stream list (health), WebRTC signalling,
// the MSE websocket and the restart the gateway triggers. Everything else (configuration, stream
// dumps with credentials, mp4/hls/mjpeg consumers, the web UI) answers 404 even with credentials.
var apiAllowedPaths = []string{"/api/streams", "/api/webrtc", "/api/ws", "/api/restart"}

// disabledSourcePaths turns go2rtc's exec and echo sources off: their allow lists name one
// executable that does not exist.
const disabledSourcePath = "/nonexistent-executable"

// DefaultRenderOptions are the values the bundled Compose file uses.
func DefaultRenderOptions() RenderOptions {
	return RenderOptions{APIListen: ":1984", WebRTCListen: ":8555", LogLevel: "error"}
}

// quote renders a YAML double-quoted scalar. JSON string syntax is a subset of YAML's.
func quote(value string) string {
	var out bytes.Buffer
	encoder := json.NewEncoder(&out)
	encoder.SetEscapeHTML(false)
	_ = encoder.Encode(value)
	return strings.TrimSpace(out.String())
}

// RenderGo2RTC renders go2rtc's YAML configuration: the API on the internal address, the WebRTC
// media port, no static/UI directory, no RTSP/SRTP server and one stream per camera. The output is
// deterministic (sorted by stream name) so an unchanged configuration yields an identical file and
// does not restart go2rtc.
func RenderGo2RTC(cameras []Camera, options RenderOptions) string {
	if !ValidLogLevel(options.LogLevel) {
		options.LogLevel = "error"
	}
	sorted := append([]Camera(nil), cameras...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].StreamName < sorted[j].StreamName })
	var b strings.Builder
	b.WriteString("# Generated by the Makerspace streaming gateway. Changes are overwritten.\n")
	b.WriteString("api:\n  listen: " + quote(options.APIListen) + "\n")
	if options.APIUsername != "" && options.APIPassword != "" {
		b.WriteString(
			"  username: " + quote(options.APIUsername) + "\n  password: " + quote(options.APIPassword) + "\n",
		)
	}
	b.WriteString("  allow_paths:\n")
	for _, path := range apiAllowedPaths {
		b.WriteString("    - " + quote(path) + "\n")
	}
	b.WriteString("log:\n  level: " + quote(options.LogLevel) + "\n")
	b.WriteString("exec:\n  allow_paths:\n    - " + quote(disabledSourcePath) + "\n")
	b.WriteString("echo:\n  allow_paths:\n    - " + quote(disabledSourcePath) + "\n")
	b.WriteString("rtsp:\n  listen: \"\"\n")
	b.WriteString("srtp:\n  listen: \"\"\n")
	b.WriteString("webrtc:\n  listen: " + quote(options.WebRTCListen) + "\n")
	if len(options.WebRTCCandidates) > 0 {
		b.WriteString("  candidates:\n")
		for _, candidate := range options.WebRTCCandidates {
			b.WriteString("    - " + quote(candidate) + "\n")
		}
	}
	if len(sorted) == 0 {
		b.WriteString("streams: {}\n")
		return b.String()
	}
	b.WriteString("streams:\n")
	for _, camera := range sorted {
		// go2rtc expands ${VAR} in its configuration; keep a literal dollar sign out of the source.
		source := strings.ReplaceAll(camera.SourceURL, "$", "%24")
		b.WriteString("  " + quote(camera.StreamName) + ":\n    - " + quote(source) + "\n")
	}
	return b.String()
}

// ConfigHash identifies a rendered configuration.
func ConfigHash(rendered string) string {
	sum := sha256.Sum256([]byte(rendered))
	return hex.EncodeToString(sum[:])
}

// WriteFileAtomic replaces path with content (mode 0600: the file contains camera credentials).
func WriteFileAtomic(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	temporary := path + ".tmp"
	if err := os.WriteFile(temporary, []byte(content), 0o600); err != nil {
		return err
	}
	return os.Rename(temporary, path)
}

// StreamStatus is what the gateway learns about one stream from go2rtc's /api/streams.
type StreamStatus struct {
	Producers     int
	Receivers     int
	Consumers     int
	Codec         *string
	Width, Height *int
	FPS           *float64
}

// Go2RTC is the control surface of the bundled go2rtc.
type Go2RTC interface {
	Streams(ctx context.Context) (map[string]StreamStatus, error)
	Restart(ctx context.Context) error
}

// ErrGo2RTCDown means go2rtc's API could not be reached at all.
var ErrGo2RTCDown = errors.New("go2rtc API is unreachable")

// Go2RTCClient talks to go2rtc's HTTP API on the internal address.
type Go2RTCClient struct {
	base *url.URL
	http *http.Client

	mu                 sync.RWMutex
	username, password string
}

// SetCredentials sets the HTTP Basic credentials sent with every request.
func (c *Go2RTCClient) SetCredentials(username, password string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.username, c.password = username, password
}

func (c *Go2RTCClient) authorize(request *http.Request) {
	c.mu.RLock()
	defer c.mu.RUnlock()
	if c.username != "" {
		request.SetBasicAuth(c.username, c.password)
	}
}

func NewGo2RTCClient(rawURL string) (*Go2RTCClient, error) {
	base, err := url.Parse(strings.TrimRight(rawURL, "/"))
	if err != nil || base.Host == "" || (base.Scheme != "http" && base.Scheme != "https") {
		return nil, errors.New("GO2RTC_API_URL must be an absolute http(s) URL")
	}
	return &Go2RTCClient{
		base: base,
		http: &http.Client{
			Timeout:       5 * time.Second,
			CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse },
		},
	}, nil
}

// BaseURL is the go2rtc API address the reverse proxy forwards to.
func (c *Go2RTCClient) BaseURL() *url.URL { u := *c.base; return &u }

type rawStream struct {
	Producers []struct {
		Receivers []struct {
			Codec struct {
				Name   string  `json:"codec_name"`
				Width  int     `json:"width"`
				Height int     `json:"height"`
				FPS    float64 `json:"fps"`
			} `json:"codec"`
		} `json:"receivers"`
	} `json:"producers"`
	Consumers []json.RawMessage `json:"consumers"`
}

// ParseStreams reduces go2rtc's /api/streams document. Producer URLs (which carry camera
// credentials) are never read.
func ParseStreams(body []byte) (map[string]StreamStatus, error) {
	var raw map[string]rawStream
	if err := json.Unmarshal(body, &raw); err != nil {
		return nil, err
	}
	result := make(map[string]StreamStatus, len(raw))
	for name, stream := range raw {
		status := StreamStatus{Producers: len(stream.Producers), Consumers: len(stream.Consumers)}
		for _, producer := range stream.Producers {
			for _, receiver := range producer.Receivers {
				status.Receivers++
				if status.Codec == nil && receiver.Codec.Name != "" && len(receiver.Codec.Name) <= 40 {
					codec := receiver.Codec.Name
					status.Codec = &codec
				}
				if status.Width == nil && receiver.Codec.Width > 0 && receiver.Codec.Height > 0 {
					w, h := receiver.Codec.Width, receiver.Codec.Height
					status.Width, status.Height = &w, &h
				}
				if status.FPS == nil && receiver.Codec.FPS > 0 {
					f := receiver.Codec.FPS
					status.FPS = &f
				}
			}
		}
		result[name] = status
	}
	return result, nil
}

func (c *Go2RTCClient) Streams(ctx context.Context) (map[string]StreamStatus, error) {
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, c.base.String()+"/api/streams", nil)
	if err != nil {
		return nil, err
	}
	c.authorize(request)
	response, err := c.http.Do(request)
	if err != nil {
		return nil, fmt.Errorf("%w", ErrGo2RTCDown)
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("go2rtc streams answered %d", response.StatusCode)
	}
	body, err := io.ReadAll(io.LimitReader(response.Body, 4<<20))
	if err != nil {
		return nil, err
	}
	return ParseStreams(body)
}

// Restart asks go2rtc to restart itself so that it re-reads its configuration file
// (POST /api/restart). Connected viewers are dropped and reconnect.
func (c *Go2RTCClient) Restart(ctx context.Context) error {
	request, err := http.NewRequestWithContext(ctx, http.MethodPost, c.base.String()+"/api/restart", nil)
	if err != nil {
		return err
	}
	c.authorize(request)
	response, err := c.http.Do(request)
	if err != nil {
		// go2rtc may drop the connection while re-executing itself; a connection that never
		// opened is reported as "down" so the caller can tell the two apart.
		var urlErr *url.Error
		if errors.As(err, &urlErr) && strings.Contains(urlErr.Error(), "connection refused") {
			return ErrGo2RTCDown
		}
		return nil
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode >= 300 {
		return fmt.Errorf("go2rtc restart answered %d", response.StatusCode)
	}
	return nil
}

// HealthFor derives the camera health reported to Core. go2rtc connects to a printer lazily, on the
// first viewer, so an idle stream is the normal resting state; a viewer without any receiving
// producer means the printer camera is not delivering media.
func HealthFor(status StreamStatus, known bool) string {
	switch {
	case !known:
		return "unavailable"
	case status.Consumers == 0:
		return "idle"
	case status.Receivers > 0:
		return "live"
	default:
		return "unavailable"
	}
}
