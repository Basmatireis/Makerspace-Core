// longTransferTimeout bounds a single timelapse upload or archive download; the
// regular client timeout is too short for videos of several hundred megabytes.
const longTransferTimeout = time.Hour

// CoreCommand is an open command Core lists for this connector.
type CoreCommand struct {
	ID           uuid.UUID `json:"id"`
	AssignmentID uuid.UUID `json:"assignmentId"`
	RunID        uuid.UUID `json:"runId"`
	Kind         string    `json:"kind"`
	State        string    `json:"state"`
}

// TimelapseUpload is a staged timelapse video ready for Core.
type TimelapseUpload struct {
	AssignmentID, RunID uuid.UUID
	FileName            string
	StagedPath          string
	SizeBytes           int64
	SHA256              string
}

func (c *Client) longClient() *http.Client {
	return &http.Client{
		Transport:     c.http.Transport,
		CheckRedirect: func(_ *http.Request, _ []*http.Request) error { return http.ErrUseLastResponse },
	}
}

// PutRunReport sends the latest report of one run.
func (c *Client) PutRunReport(ctx context.Context, token string, report PendingRunReport) error {
	body := map[string]any{
		"protocolVersion": 1,
		"observedAt":      report.ObservedAt.UTC(),
		"consumption":     report.Consumption,
		"timelapse":       report.Timelapse,
	}
	return c.do(
		ctx,
		http.MethodPut,
		fmt.Sprintf("/printer-connector/self/assignments/%s/runs/%s/report", report.AssignmentID, report.RunID),
		token,
		body,
		nil,
	)
}

// ListCommands returns the open commands Core holds for this connector.
func (c *Client) ListCommands(ctx context.Context, token string) ([]CoreCommand, error) {
	var output struct {
		Items []CoreCommand `json:"items"`
	}
	err := c.do(ctx, http.MethodGet, "/printer-connector/self/commands", token, nil, &output)
	return output.Items, err
}

// PutCommandStatus reports a command's state.
func (c *Client) PutCommandStatus(ctx context.Context, token string, id uuid.UUID, state string, reason *string) error {
	return c.do(
		ctx,
		http.MethodPut,
		"/printer-connector/self/commands/"+id.String()+"/status",
		token,
		map[string]any{"state": state, "reasonCode": reason},
		nil,
	)
}

// DownloadRunArtifact streams the 3MF Core stores for a run into writer and
// verifies it against the SHA-256 Core declares. At most limit bytes are read.
func (c *Client) DownloadRunArtifact(
	ctx context.Context,
	token string,
	assignmentID, runID uuid.UUID,
	writer io.Writer,
	limit int64,
) error {
	ctx, cancel := context.WithTimeout(ctx, longTransferTimeout)
	defer cancel()
	request, err := http.NewRequestWithContext(
		ctx,
		http.MethodGet,
		fmt.Sprintf("%s/api/v1/printer-connector/self/assignments/%s/runs/%s/artifact/content", c.base, assignmentID, runID),
		nil,
	)
	if err != nil {
		return err
	}
	request.Header.Set("Authorization", "Bearer "+token)
	response, err := c.longClient().Do(request)
	if err != nil {
		return err
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode != http.StatusOK {
		return coreErrorFrom(response)
	}
	declared := response.Header.Get("X-Artifact-SHA256")
	hash := sha256.New()
	written, err := io.Copy(io.MultiWriter(writer, hash), io.LimitReader(response.Body, limit+1))
	if err != nil {
		return err
	}
	if written > limit || hex.EncodeToString(hash.Sum(nil)) != declared {
		return errors.New("downloaded artifact does not match Core's SHA-256 or exceeds the limit")
	}
	return nil
}

// UploadTimelapse streams a staged video to Core. created is false when Core
// already had these bytes.
func (c *Client) UploadTimelapse(ctx context.Context, token string, upload TimelapseUpload) (bool, error) {
	if upload.AssignmentID == uuid.Nil || upload.RunID == uuid.Nil || upload.SizeBytes < 1 || len(upload.SHA256) != 64 {
		return false, errors.New("invalid staged timelapse")
	}
	file, err := os.Open(upload.StagedPath) //nolint:gosec // staged path is generated by this process inside the data directory
	if err != nil {
		return false, err
	}
	defer func() { _ = file.Close() }()
	info, err := file.Stat()
	if err != nil {
		return false, err
	}
	if info.Size() != upload.SizeBytes {
		return false, errors.New("staged timelapse size changed")
	}
	ctx, cancel := context.WithTimeout(ctx, longTransferTimeout)
	defer cancel()
	request, err := http.NewRequestWithContext(
		ctx,
		http.MethodPut,
		fmt.Sprintf("%s/api/v1/printer-connector/self/assignments/%s/runs/%s/timelapse", c.base, upload.AssignmentID, upload.RunID),
		file,
	)
	if err != nil {
		return false, err
	}
	request.Header.Set("Authorization", "Bearer "+token)
	request.Header.Set("Content-Type", "application/octet-stream")
	request.Header.Set("X-Timelapse-Filename", upload.FileName)
	request.Header.Set("X-Timelapse-SHA256", upload.SHA256)
	request.ContentLength = upload.SizeBytes
	response, err := c.longClient().Do(request)
	if err != nil {
		return false, err
	}
	defer func() { _ = response.Body.Close() }()
	switch response.StatusCode {
	case http.StatusCreated:
		return true, nil
	case http.StatusOK:
		return false, nil
	default:
		return false, coreErrorFrom(response)
	}
}

func coreErrorFrom(response *http.Response) error {
	var apiError struct{ Code, Message string }
	_ = json.NewDecoder(io.LimitReader(response.Body, 1<<20)).Decode(&apiError)
	if apiError.Code == "" {
		apiError.Code = strconv.Itoa(response.StatusCode)
	}
	return &CoreError{Status: response.StatusCode, Code: apiError.Code}
}
